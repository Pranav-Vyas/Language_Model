"""Generate the Phase-3 reasoning dataset statistics table (T3.5).

Language-agnostic tooling: it reads both trees' generated data but holds no
language data of its own and never mixes the two corpora.

    python scripts/build_reasoning_stats.py

Every figure traces to a generated file or a committed evidence JSON, so a stale
number is a missing re-run rather than an undetectable typo -- the same contract
as the Phase-2 table generators.
"""

from __future__ import annotations

import argparse
import json
from collections import Counter
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
TREES = [("hindi", "Model H (Hindi)", "hi"), ("nepali", "Model L (Nepali)", "ne")]
SPLITS = ["train", "val", "test", "ood"]
PATTERN_NAME = {
    "P1": "P1 · direct 2-entity comparison",
    "P2": "P2 · transitive 2-hop (unstated pair)",
    "P3": "P3 · superlative of 3",
    "P4": "P4 · sequential / ordinal",
    "P5": "P5 · 3-hop chain (curriculum arm only)",
}


def load(tree: str, split: str) -> list[dict]:
    p = REPO / tree / "reasoning_data" / f"{split}.jsonl"
    if not p.exists():
        return []
    return [json.loads(l) for l in open(p, encoding="utf-8") if l.strip()]


def tokenise_stats(tree: str, code: str, rows: list[dict]) -> dict | None:
    """Token lengths under THIS tree's own frozen tokenizer."""
    try:
        import sentencepiece as spm
    except ImportError:
        return None
    mp = REPO / tree / "tokenizer" / f"{code}_bpe_16000.model"
    if not mp.exists():
        return None
    sp = spm.SentencePieceProcessor(model_file=str(mp))
    pl, tl, unk = [], [], 0
    for r in rows[:5000]:
        p = sp.encode(r["prompt"]); t = sp.encode(r["target_answer_only"])
        pl.append(len(p)); tl.append(len(t))
        unk += sum(1 for i in p + t if i == sp.unk_id())
    return {"prompt_mean": sum(pl) / len(pl), "prompt_max": max(pl),
            "target_mean": sum(tl) / len(tl), "unk": unk, "sampled": len(pl)}


def table(rows: list[str]) -> list[str]:
    return rows


def main(argv=None) -> None:
    ap = argparse.ArgumentParser(description="Build the reasoning stats table.")
    ap.add_argument("--out", default=str(REPO / "report" / "phase3" / "dataset_stats.md"))
    args = ap.parse_args(argv)

    doc = ["# Phase 3 — synthetic reasoning dataset statistics", "",
           "Generated by `scripts/build_reasoning_stats.py` from the files that "
           "`<lang>/reasoning/generate.py` produces. Do not edit by hand.", "",
           "The two datasets are **independent**: separate generators in separate "
           "trees, separate frozen tokenizers, separate weights, and templates "
           "written from each language's own corpus evidence rather than "
           "translated. The two entity pools are NOT name-disjoint and are not "
           "required to be — most South Asian given names are shared across both "
           "languages, and forcing disjointness is what previously pushed the "
           "Nepali pool into common nouns. Pool SIZE is held identical, because "
           "that would affect the H-vs-L comparison.", ""]

    # --- size -------------------------------------------------------------
    doc += ["## Size", "", "| split | " + " | ".join(l for _, l, _ in TREES) + " | role |",
            "|---|" + "---|" * (len(TREES) + 1)]
    roles = {"train": "training", "val": "held-out entity names",
             "test": "held-out names **and** 2 unseen relations",
             "ood": "4-hop chains (P6), a depth never trained"}
    for s in SPLITS:
        cells = [f"{len(load(t, s)):,}" for t, _, _ in TREES]
        doc.append(f"| {s} | " + " | ".join(cells) + f" | {roles[s]} |")
    doc.append("")

    # --- composition ------------------------------------------------------
    doc += ["## Pattern composition (train)", "",
            "| pattern | " + " | ".join(l for _, l, _ in TREES) + " | type |",
            "|---|" + "---|" * (len(TREES) + 1)]
    tr = {t: load(t, "train") for t, _, _ in TREES}
    counts = {t: Counter(r["pattern"] for r in rows) for t, rows in tr.items()}
    for pat in ["P1", "P2", "P3", "P4"]:
        cells = [f"{counts[t][pat]:,} ({counts[t][pat]/len(tr[t])*100:.1f}%)"
                 for t, _, _ in TREES]
        kind = "atomic" if pat == "P1" else "inferred"
        doc.append(f"| {PATTERN_NAME[pat]} | " + " | ".join(cells) + f" | {kind} |")
    for t, _, _ in TREES:
        pass
    inf = {t: sum(counts[t][p] for p in ("P2", "P3", "P4")) for t, _, _ in TREES}
    cells = [f"{inf[t]/counts[t]['P1']:.2f} : 1" for t, _, _ in TREES]
    doc += ["| **inferred : atomic ratio** | " + " | ".join(f"**{c}**" for c in cells)
            + " | the mix knob |", "",
            "> Biased toward multi-hop deliberately. On comparison tasks the ratio of "
            "inferred to atomic examples drives how fast generalisation appears, and "
            "matters more than the absolute dataset size.", ""]

    # --- template variety -------------------------------------------------
    doc += ["## Template variety", "",
            "| | " + " | ".join(l for _, l, _ in TREES) + " |",
            "|---|" + "---|" * len(TREES)]
    for label, fn in [
        ("relations in train", lambda rows: len({r["relation"] for r in rows})),
        ("relations in test", None),
        ("distinct prompts (train)", lambda rows: len({r["prompt"] for r in rows})),
        ("entity names in train", lambda rows: len({e for r in rows for e in r["chain"]})),
    ]:
        if label == "relations in test":
            cells = [str(len({r["relation"] for r in load(t, "test")})) for t, _, _ in TREES]
        else:
            cells = [f"{fn(tr[t]):,}" for t, _, _ in TREES]
        doc.append(f"| {label} | " + " | ".join(cells) + " |")
    doc.append("")

    # --- tokenisation -----------------------------------------------------
    doc += ["## Tokenisation, under each model's own frozen tokenizer", "",
            "| | " + " | ".join(l for _, l, _ in TREES) + " |",
            "|---|" + "---|" * len(TREES)]
    ts = {t: tokenise_stats(t, c, tr[t]) for t, _, c in TREES}
    if all(ts.values()):
        for label, key, fmt in [("prompt tokens (mean)", "prompt_mean", ".1f"),
                                ("prompt tokens (max)", "prompt_max", "d"),
                                ("target tokens (mean)", "target_mean", ".1f"),
                                ("**UNK tokens**", "unk", "d")]:
            cells = [format(ts[t][key], fmt) for t, _, _ in TREES]
            doc.append(f"| {label} | " + " | ".join(cells) + " |")
        doc += ["", "> Context for finetuning is 128, comfortably above the longest "
                "prompt. Zero UNK matters: an out-of-vocabulary token would make the "
                "example test tokenizer robustness rather than reasoning.", ""]

    # --- heuristic baselines ---------------------------------------------
    doc += ["## Surface-heuristic baselines (train)", "",
            "A guesser that always names the first- or last-mentioned entity must not "
            "beat chance, or a high accuracy would prove nothing. Premise order is "
            "shuffled, question polarity is balanced, and each premise is randomly "
            "surfaced with the adjective or its antonym.", "",
            "| | " + " | ".join(l for _, l, _ in TREES) + " |",
            "|---|" + "---|" * len(TREES)]
    for label, fn in [
        ("random-among-candidates (chance)",
         lambda rows: sum(1 / len(r["candidates"]) for r in rows) / len(rows)),
        ("always first-mentioned",
         lambda rows: sum(r["answer"] == r["first_mention"] for r in rows) / len(rows)),
        ("always last-mentioned",
         lambda rows: sum(r["answer"] == r["last_mention"] for r in rows) / len(rows)),
        ("majority answer",
         lambda rows: max(Counter(r["answer"] for r in rows).values()) / len(rows)),
    ]:
        cells = [f"{fn(tr[t]):.3f}" for t, _, _ in TREES]
        doc.append(f"| {label} | " + " | ".join(cells) + " |")
    doc.append("")

    # --- leakage ----------------------------------------------------------
    doc += ["## Anti-leakage verification", "",
            "Produced by `<lang>/reasoning/verify_leakage.py`, run against the "
            "generated files rather than the pools that were meant to produce them.", "",
            "| check | " + " | ".join(l for _, l, _ in TREES) + " |",
            "|---|" + "---|" * len(TREES)]
    lk = {}
    for t, _, _ in TREES:
        p = REPO / "report" / "phase3" / t / "leakage_check.json"
        lk[t] = json.loads(p.read_text()) if p.exists() else None
    if all(lk.values()):
        names = [c["name"] for c in lk[TREES[0][0]]["checks"]]
        for nm in names:
            cells = []
            for t, _, _ in TREES:
                c = next(x for x in lk[t]["checks"] if x["name"] == nm)
                cells.append("PASS" if c["passed"] else "**FAIL**")
            doc.append(f"| {nm} | " + " | ".join(cells) + " |")
        doc += ["", "> The 8-gram overlap between train and test is *reported, not "
                "gated*: the train and test entity pools are disjoint, so any shared span is template "
                "scaffolding and cannot carry an answer. N-gram decontamination is "
                "necessary but not sufficient — it cannot detect paraphrase — so the "
                "structural holdouts above are the load-bearing guarantees.", ""]

    out = Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(doc) + "\n", encoding="utf-8")
    print(f"wrote {out} ({len(doc)} lines)")


if __name__ == "__main__":
    main()
